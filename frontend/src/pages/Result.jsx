import logo from "../assets/Logo.png";
import {
  FaArrowLeft,
  FaChartBar,
  FaFileAlt,
  FaTools,
  FaStar,
  FaBriefcase,
  FaChartLine,
  FaLightbulb,
  FaTimesCircle,
  FaCheckCircle,
  FaDownload,
  FaCopy
} from "react-icons/fa";
import jsPDF from "jspdf";
